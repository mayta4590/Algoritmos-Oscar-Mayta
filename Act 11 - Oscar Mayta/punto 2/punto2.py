#2. Calcular el sueldo mensual de un operario conociendo la cantidad de horas trabajadas y el valor por hora.

cantidaddehoras=int(input("Ingrese la cantidad de horas que trabajo el operario: "))
valorporhora=int(input("Ingrese el valor por hora: "))

sueldomensual=cantidaddehoras*valorporhora

print("El sueldo mensual del operario es: ")
print(sueldomensual)